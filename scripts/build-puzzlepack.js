// Verify every selected Lichess puzzle with the app's own rules engine, then write js/data/puzzlepack.js.
// Usage: node scripts/build-puzzlepack.js [selected.json] [js/data/puzzlepack.js] [pack]
//   (the second pack: node scripts/build-puzzlepack.js selected2.json js/data/puzzlepack2.js pack2)
const C = require(require('path').join(__dirname, '../js/chess.js'));
const fs = require('fs'), path = require('path');
const IN = process.argv[2] || 'selected.json', OUT = process.argv[3] || path.join(__dirname, '../js/data/puzzlepack.js'), NAME = process.argv[4] || 'pack';
const sel = JSON.parse(fs.readFileSync(IN, 'utf8'));
const themeList = [], openList = [''];
const ti = t => { let i = themeList.indexOf(t); if (i < 0) { i = themeList.length; themeList.push(t); } return i; };
const oi = o => { let i = openList.indexOf(o); if (i < 0) { i = openList.length; openList.push(o); } return i; };
const rows = []; const bad = {};
for (const p of sel) {
  let g; try { g = new C(p.fen); } catch (e) { bad.fen = (bad.fen || 0) + 1; continue; }
  const mv = p.moves.split(' ');
  let ok = true;
  for (const u of mv) { const m = g.move({ from: u.slice(0, 2), to: u.slice(2, 4), promotion: u[4] }); if (!m) { ok = false; break; } }
  if (!ok) { bad.illegal = (bad.illegal || 0) + 1; continue; }
  const th = p.themes.split(' ');
  if (th.includes('mate') && !g.isCheckmate()) { bad.notMate = (bad.notMate || 0) + 1; continue; }
  const mi = th.find(t => /^mateIn\d$/.test(t));
  if (mi && +mi.slice(6) !== mv.length / 2) { bad.mateLen = (bad.mateLen || 0) + 1; continue; }
  if (mv.length % 2 !== 0) { bad.odd = (bad.odd || 0) + 1; continue; }
  const drop = new Set(['short', 'long', 'veryLong', 'oneMove', 'master', 'masterVsMaster', 'superGM', 'middlegame', 'opening', 'endgame']);
  const keep = th.filter(t => !drop.has(t)).map(ti).join('.');
  const op = p.open ? oi(p.var && /Alapin|Advance|London|Classical|Two_Knights|Panov|Exchange|Vienna|Mieses/.test(p.var) ? p.var : p.open) : 0;
  const phase = th.includes('opening') ? 'o' : th.includes('endgame') ? 'e' : 'm';
  rows.push([p.id, p.fen, p.moves, p.rating, keep, op, p.flag + phase].join('|'));
}
const out = '/* Puzzle pack: ' + rows.length + ' puzzles from the Lichess puzzle database (lichess.org), released under CC0 (public domain).\n' +
  ' * Every move was replayed with the app\'s rules engine; mate puzzles were confirmed to end in checkmate.\n' +
  ' * Row: id|FEN before the opponent\'s move|UCI moves (first = opponent)|Lichess rating|theme indexes|opening index|flags (W=Woodpecker set, O=your openings, A=advanced, E=endgame, H=harder 1000+, B=back-rank combination; then phase o/m/e).\n' +
  ' * Generated by scripts/build-puzzlepack.js from ' + path.basename(IN) + '. */\n' +
  '(function (root) {\n  root.CT = root.CT || {}; root.CT.Data = root.CT.Data || {};\n  root.CT.Data.' + NAME + ' = {\n    themes: ' + JSON.stringify(themeList) + ',\n    openings: ' + JSON.stringify(openList) + ',\n    rows: ' + JSON.stringify(rows.join('\n')) + '\n  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(OUT, out);
console.log(rows.length, 'verified;', 'rejected:', JSON.stringify(bad), '; size', (out.length / 1024).toFixed(0) + ' KB');
console.log('openings:', openList.length, openList.slice(0, 25).join(', '));
